"""Shared benchmark-environment reporting.

Two jobs. First, say where the PDS-H data lives: the tables are generated by
the pola-rs/polars-benchmark checkout itself (`make data-tables
SCALE_FACTOR=<sf>.0`, i.e. tpchgen-cli then Polars' own parquet writer), never
by Ibex, so nobody can call the comparison fudged by an Ibex-friendly layout.

Second, put the scale factor on the face of every result. The TPC-H queries
read `benchmarking/data/tpch/parquet`, a SYMLINK that run_bench.sh and
check_answers.py repoint at `<pdsh-root>/data/tables/scale-<sf>/`. Three separate sessions have now
compared absolute timings from two different scale factors and concluded the
engine (or the machine) had changed, because no harness printed which dataset
produced the number. A ~2x or ~4x discrepancy between two runs of the same
binary is a scale factor until proven otherwise.
"""
import os
import pathlib

PARQUET_LINK = pathlib.Path(__file__).resolve().parent / "data/tpch/parquet"


def default_pdsh_root() -> pathlib.Path:
    """$PDSH_ROOT, else ~/polars-benchmark (run_bench.sh searches the same way)."""
    return pathlib.Path(os.environ.get("PDSH_ROOT", pathlib.Path.home() / "polars-benchmark"))


def pdsh_tables_root(pdsh_root: pathlib.Path) -> pathlib.Path:
    """What polars-benchmark calls PATH_TABLES."""
    return pdsh_root / "data/tables"


def pdsh_scale_dir(pdsh_root: pathlib.Path, sf) -> pathlib.Path:
    """The generated tables for one scale factor.

    polars-benchmark formats the scale as a float, so SF 8 lives in
    `scale-8.0`, not `scale-8`.
    """
    return pdsh_tables_root(pdsh_root) / f"scale-{float(sf)}"


def point_parquet_link(target: pathlib.Path, link: pathlib.Path = PARQUET_LINK) -> None:
    """Repoint the path the queries read at `target` (absolute)."""
    if link.is_symlink() or not link.exists():
        link.unlink(missing_ok=True)
    else:
        raise RuntimeError(f"{link} is not a symlink; refusing to replace it")
    link.symlink_to(target.resolve())


def parquet_link_points_at(target: pathlib.Path, link: pathlib.Path = PARQUET_LINK) -> bool:
    return link.is_symlink() and link.resolve() == target.resolve()


def scale_factor_line(link: pathlib.Path = PARQUET_LINK) -> str:
    """A one-line '# dataset: ...' banner naming the dataset actually in use."""
    try:
        target = str(link.readlink()) if link.is_symlink() else link.name
    except OSError as exc:
        return f"# dataset: UNREADABLE ({exc}) — {link}"
    if not link.exists():
        return f"# dataset: {target} — BROKEN LINK, queries will fail"
    return f"# dataset: {target}  ({link})"
